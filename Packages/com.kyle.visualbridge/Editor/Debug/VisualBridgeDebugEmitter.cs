    /// <summary>一个计划写入的产物；字节在内存里算好，写盘前就能做完整比较（Check）。</summary>
    internal sealed class VisualBridgeDebugPlannedFile
    {
        public VisualBridgeDebugPlannedFile(string relativePath, string fullPath, string text)
        {
            RelativePath = relativePath;
            FullPath = fullPath;
            Bytes = new UTF8Encoding(false).GetBytes(text);
            Sha256 = VisualBridgeDebugContractHash.HashFile(Bytes);
        }

        public string RelativePath { get; }

        public string FullPath { get; }

        public byte[] Bytes { get; }

        public string Sha256 { get; }

        public string Text => Encoding.UTF8.GetString(Bytes);
    }

    /// <summary>
    /// 产物发射（附录 B.5 的产物清单）：C# 门面/实现/分发器/分类协议、全局契约与指纹。
    /// 所有产物在内存中一次算完；任何校验都发生在写盘之前，失败不会留下半份产物。
    /// 生成的事件实现按参数 tag 升序调用 PushParam（附录 A.4 的稀疏参数区）。
    /// </summary>
    internal static partial class VisualBridgeDebugEmitter
    {
        private const string Header =
            "// <auto-generated />\n"
            + "// 由 VisualBridge 调试契约生成器（D2）产出；请勿手工修改：改写会被 Generate/Check 判为 drift。\n";

        private const string RuntimeGuard = "#if UNITY_EDITOR || VISUALBRIDGE_RUNTIME_BRIDGE";
        private const string GeneratedNamespace = "VisualBridge.Diagnostics.Generated";
        private const string DebugApi = "global::VisualBridge.Diagnostics.VisualBridgeDebug";
        private const string RequestType = "global::VisualBridge.Diagnostics.VisualBridgeDebugRequest";

        /// <summary>发射全部产物；OrderBy 保证计划顺序稳定。</summary>
        public static IReadOnlyList<VisualBridgeDebugPlannedFile> EmitAll(
            VisualBridgeDebugDefinitionModel definition,
            VisualBridgeDebugIdState idsState,
            string projectRoot,
            string artifactsRootRelative)
        {
            var contractHash = VisualBridgeDebugContractHash.Compute(definition);
            var files = new List<VisualBridgeDebugPlannedFile>();
            foreach (var category in definition.Categories)
            {
                files.AddRange(EmitCategory(category, definition, contractHash, projectRoot));
                foreach (var contractInterface in category.Interfaces)
                {
                    files.Add(EmitFacade(contractInterface, projectRoot));
                    files.Add(contractInterface.Kind == VisualBridgeDebugerKind.Event
                        ? EmitImplementation(contractInterface, projectRoot)
                        : EmitDispatcher(contractInterface, projectRoot));
                }
            }

            files.Add(EmitContractsJson(definition, contractHash, projectRoot, artifactsRootRelative));
            files.Add(EmitGlobalCSharp(contractHash, projectRoot, artifactsRootRelative));
            files.Add(EmitIdsJson(idsState, projectRoot, artifactsRootRelative));

            var duplicate = files
                .GroupBy(file => file.FullPath, VisualBridgeDebugGeneratorPaths.FilePathComparer)
                .FirstOrDefault(group => group.Count() > 1);
            if (duplicate != null)
            {
                throw new VisualBridgeDebugGeneratorException(
                    "debug.outputConflict",
                    "多个契约输入计划写同一个产物文件：" + duplicate.Key);
            }

            return files.OrderBy(file => file.RelativePath, StringComparer.Ordinal).ToArray();
        }

        private static IEnumerable<VisualBridgeDebugPlannedFile> EmitCategory(
            VisualBridgeDebugCategoryModel category,
            VisualBridgeDebugDefinitionModel definition,
            string contractHash,
            string projectRoot)
        {
            yield return EmitCategoryProtocol(category, projectRoot);
            yield return EmitCategoryTypeScript(category, definition, contractHash, projectRoot);
        }

        private static VisualBridgeDebugPlannedFile EmitCategoryProtocol(
            VisualBridgeDebugCategoryModel category,
            string projectRoot)
        {
            var code = new CodeBuilder();
            code.Raw(Header);
            code.Line("namespace " + GeneratedNamespace);
            code.Open();
            code.Line("/// <summary>分类 \"" + category.Name + "\" 的接口方法号（附录 B.5）：只含接口方法，业务方法从 10 起。</summary>");
            code.Line("public static class " + category.TypeName);
            code.Open();
            code.Line("/// <summary>分类名（与 [VisualBridgeDebuger] 的 Category 一致，契约文件里按字符串携带）。</summary>");
            code.Line("public const string Category = " + Literal(category.Name) + ";");
            foreach (var method in category.Interfaces
                         .SelectMany(value => value.Methods)
                         .OrderBy(value => value.Name, StringComparer.Ordinal))
            {
                code.Blank();
                code.Line("/// <summary>" + method.Name + " 的方法号；系统号段见 VisualBridgeDebugSystemMethod。</summary>");
                code.Line("public const ushort " + VisualBridgeDebugTypeMapping.CSharpIdentifier(method.Name)
                    + " = " + method.MethodId + ";");
            }

            code.Close();
            code.Close();
            return Plan(
                projectRoot,
                category.GeneratedDirectory + "/" + category.FileBaseName + "Category.g.cs",
                code.ToString());
        }

        private static VisualBridgeDebugPlannedFile EmitFacade(VisualBridgeDebugInterfaceModel model, string projectRoot)
        {
            var code = new CodeBuilder();
            code.Raw(Header);
            if (model.GeneratedNamespace.Length != 0)
            {
                code.Line("namespace " + model.GeneratedNamespace);
                code.Open();
            }

            code.Line("/// <summary><see cref=\"" + model.InterfaceFullName + "\"/> 的静态门面（附录 B.5）：");
            code.Line("/// 业务只调用这里，不手写分类名与方法号。</summary>");
            code.Line("public static class " + model.ClassName);
            code.Open();
            var first = true;
            if (model.Kind == VisualBridgeDebugerKind.Event)
            {
                foreach (var method in model.Methods)
                {
                    if (!first)
                    {
                        code.Blank();
                    }

                    first = false;
                    code.Line("/// <summary>发送 " + method.Name + " 事件（方法号 " + method.MethodId + "）；false = 消息未入队。</summary>");
                    code.Line("public static bool " + VisualBridgeDebugTypeMapping.CSharpIdentifier(method.Name)
                        + "(" + Signature(method.Parameters, true) + ")");
                    code.Open();
                    code.Raw(RuntimeGuard);
                    code.Line("return " + ImplementationName(model) + ".Try" + method.Name + "(" + Arguments(method.Parameters) + ");");
                    code.Raw("#else");
                    code.Line("return false;");
                    code.Raw("#endif");
                    code.Close();
                }
            }
            else
            {
                code.Line("/// <summary>挂载业务实现：把处理器注册到调试运行期（重复调用以最后一次为准）。</summary>");
                code.Line("public static void Register(" + model.CSharpReference + " implementation)");
                code.Open();
                code.Raw(RuntimeGuard);
                code.Line(DispatcherName(model) + ".Register(implementation);");
                code.Raw("#endif");
                code.Close();

                code.Blank();
                code.Line("/// <summary>解除挂载；不影响已建立的连接。</summary>");
                code.Line("public static void Unregister()");
                code.Open();
                code.Raw(RuntimeGuard);
                code.Line(DispatcherName(model) + ".Unregister();");
                code.Raw("#endif");
                code.Close();

                foreach (var method in model.Methods)
                {
                    code.Blank();
                    code.Line("/// <summary>回发 " + method.Name + " 的查询结果（方法号 " + method.MethodId + "）；false = 消息未入队。</summary>");
                    code.Line("public static bool Send" + method.Name + "Result(" + ResultSignature(method) + ")");
                    code.Open();
                    code.Raw(RuntimeGuard);
                    code.Line("if (!" + DebugApi + ".StartResult(request))");
                    code.Open();
                    code.Line("return false;");
                    code.Close();
                    if (method.ResultParameter != null)
                    {
                        code.Line(DebugApi + ".PushParam(" + Literal(method.ResultParameter.Name) + ", "
                            + method.ResultParameter.Tag + ", (" + method.ResultParameter.CastType + ")result);");
                    }

                    code.Line("return " + DebugApi + ".End();");
                    code.Raw("#else");
                    code.Line("return false;");
                    code.Raw("#endif");
                    code.Close();
                }
            }

            code.Close();
            if (model.GeneratedNamespace.Length != 0)
            {
                code.Close();
            }

            return Plan(
                projectRoot,
                model.GeneratedDirectory + "/" + model.ClassName + ".g.cs",
                code.ToString());
        }

        private static VisualBridgeDebugPlannedFile EmitImplementation(
            VisualBridgeDebugInterfaceModel model,
            string projectRoot)
        {
            var code = new CodeBuilder();
            code.Raw(Header);
            code.Raw(RuntimeGuard);
            if (model.GeneratedNamespace.Length != 0)
            {
                code.Line("namespace " + model.GeneratedNamespace);
                code.Open();
            }

            code.Line("/// <summary><see cref=\"" + model.InterfaceFullName + "\"/> 的生成实现（附录 B.5）：");
            code.Line("/// 逐方法调用 Start/PushParam/End；接口实现与 Try&lt;Method&gt; 共用同一段发送逻辑。</summary>");
            code.Line("public sealed class " + ImplementationName(model) + " : " + model.CSharpReference);
            code.Open();
            code.Line("/// <summary>无状态单例：需要 I" + model.ClassName + " 的适配器可以直接注入它。</summary>");
            code.Line("public static readonly " + ImplementationName(model) + " Instance = new " + ImplementationName(model) + "();");
            code.Blank();
            code.Line("private " + ImplementationName(model) + "()");
            code.Open();
            code.Close();

            foreach (var method in model.Methods)
            {
                code.Blank();
                code.Line("/// <inheritdoc />");
                code.Line("public bool " + VisualBridgeDebugTypeMapping.CSharpIdentifier(method.Name)
                    + "(" + Signature(method.Parameters, false) + ")");
                code.Open();
                code.Line("return Try" + method.Name + "(" + Arguments(method.Parameters) + ");");
                code.Close();
            }

            foreach (var method in model.Methods)
            {
                code.Blank();
                code.Line("/// <summary>发送 " + method.Name + " 事件（方法号 " + method.MethodId + "）；false = 消息未入队。</summary>");
                code.Line("public static bool Try" + method.Name + "(" + Signature(method.Parameters, false) + ")");
                code.Open();
                code.Line("if (!" + DebugApi + ".Start("
                    + VisualBridgeDebugTypeMapping.CSharpIdentifier(method.InstanceParameter.Name) + ", "
                    + Literal(model.Category) + ", "
                    + method.MethodId + ", "
                    + Literal(model.InterfaceName) + ", "
                    + Literal(method.Name) + "))");
                code.Open();
                code.Line("return false;");
                code.Close();

                // 附录 A.4：参数区按 tag 升序写出；这里按 tag 排序，而不是按声明顺序。
                var payload = method.PayloadParameters.OrderBy(parameter => parameter.Tag).ToArray();
                if (payload.Length != 0)
                {
                    code.Blank();
                    foreach (var parameter in payload)
                    {
                        code.Line(DebugApi + ".PushParam(" + Literal(parameter.Name) + ", " + parameter.Tag
                            + ", (" + parameter.CastType + ")" + VisualBridgeDebugTypeMapping.CSharpIdentifier(parameter.Name) + ");");
                    }
                }

                code.Line("return " + DebugApi + ".End();");
                code.Close();
            }

            code.Close();
            if (model.GeneratedNamespace.Length != 0)
            {
                code.Close();
            }

            code.Raw("#endif");
            return Plan(
                projectRoot,
                model.GeneratedDirectory + "/" + ImplementationName(model) + ".g.cs",
                code.ToString());
        }

        private static VisualBridgeDebugPlannedFile EmitDispatcher(
            VisualBridgeDebugInterfaceModel model,
            string projectRoot)
        {
            var code = new CodeBuilder();
            code.Raw(Header);
            code.Raw(RuntimeGuard);
            if (model.GeneratedNamespace.Length != 0)
            {
                code.Line("namespace " + model.GeneratedNamespace);
                code.Open();
            }

            code.Line("/// <summary>");
            code.Line("/// Query 接口 <see cref=\"" + model.InterfaceFullName + "\"/> 的请求分发（附录 B.5）：Register 时挂载处理器与");
            code.Line("/// 参数声明表，收到请求后构造携带 category / iface / method 的 VisualBridgeDebugRequest 并调用业务实现，");
            code.Line("/// 结果由门面 Send&lt;Method&gt;Result 回发；业务实现抛异常时回发 RejectRequest 并返回 false。");
            code.Line("/// </summary>");
            code.Line("public static class " + DispatcherName(model));
            code.Open();
            code.Line("private static " + model.CSharpReference + " s_implementation;");
            code.Blank();
            code.Line("/// <summary>挂载业务实现并注册处理器；解码表让运行期按声明顺序解出载荷参数。</summary>");
            code.Line("public static void Register(" + model.CSharpReference + " implementation)");
            code.Open();
            code.Line("s_implementation = implementation;");
            code.Line(DebugApi + ".RegisterRequestHandler(");
            code.Line("    " + Literal(model.Category) + ",");
            code.Line("    " + Literal(model.InterfaceName) + ",");
            code.Line("    new global::VisualBridge.Diagnostics.VisualBridgeDebugRequestDispatcher(Dispatch),");
            code.Line("    new global::VisualBridge.Diagnostics.VisualBridgeDebugRequestParameterDecoder(TryGetParameters));");
            code.Close();
            code.Blank();
            code.Line("/// <summary>解除挂载；处理器随之从运行期移除。</summary>");
            code.Line("public static void Unregister()");
            code.Open();
            code.Line("s_implementation = null;");
            code.Line(DebugApi + ".RegisterRequestHandler(" + Literal(model.Category) + ", " + Literal(model.InterfaceName) + ", null);");
            code.Close();
            code.Blank();
            code.Line("/// <summary>按方法号分发；false = 未知方法号、未挂载或业务实现抛异常（异常已回发 RejectRequest）。</summary>");
            code.Line("public static bool Dispatch(ushort methodId, string instanceId, ushort instanceSlot, uint requestSeq, object[] parameters)");
            code.Open();
            code.Line("switch (methodId)");
            code.Open();
            foreach (var method in model.Methods)
            {
                code.Line("case " + method.MethodId + ":");
                code.Line("    return Dispatch" + method.Name + "(CreateRequest(instanceId, instanceSlot, methodId, requestSeq, "
                    + Literal(method.Name) + "), parameters);");
            }

            code.Line("default:");
            code.Line("    return false;");
            code.Close();
            code.Close();
            code.Blank();
            code.Line("/// <summary>");
            code.Line("/// 构造携带结果归属的请求句柄（附录 B.2.3 的 7 参构造）：运行期不再反射生成成员，");
            code.Line("/// 因此 IL2CPP 裁剪也不会让 debugResult 的 iface / method 静默缺失。");
            code.Line("/// </summary>");
            code.Line("private static " + RequestType + " CreateRequest(string instanceId, ushort instanceSlot, ushort methodId,");
            code.Line("    uint requestSeq, string method)");
            code.Open();
            code.Line("return new " + RequestType + "(instanceId, instanceSlot, methodId, requestSeq,");
            code.Line("    " + Literal(model.Category) + ", " + Literal(model.InterfaceName) + ", method);");
            code.Close();
            code.Blank();
            code.Line("/// <summary>方法号 → 方法名（诊断用；运行期不再依赖它来补齐结果归属，附录 B.5）。</summary>");
            code.Line("public static bool TryGetMethodName(ushort methodId, out string methodName)");
            code.Open();
            code.Line("switch (methodId)");
            code.Open();
            foreach (var method in model.Methods)
            {
                code.Line("case " + method.MethodId + ":");
                code.Line("    methodName = " + Literal(method.Name) + ";");
                code.Line("    return true;");
            }

            code.Line("default:");
            code.Line("    methodName = null;");
            code.Line("    return false;");
            code.Close();
            code.Close();
            code.Blank();
            code.Line("/// <summary>方法号 → 载荷参数名/tag/类型（顺序与业务方法一致，不含请求句柄；供查询运行期解码）。</summary>");
            code.Line("public static bool TryGetParameters(");
            code.Line("    ushort methodId,");
            code.Line("    out string[] names,");
            code.Line("    out ushort[] tags,");
            code.Line("    out global::System.Type[] types)");
            code.Open();
            code.Line("switch (methodId)");
            code.Open();
            foreach (var method in model.Methods)
            {
                var payload = method.PayloadParameters.ToArray();
                code.Line("case " + method.MethodId + ":");
                code.Line("    names = new string[] { " + string.Join(", ", payload.Select(value => Literal(value.Name))) + " };");
                code.Line("    tags = new ushort[] { " + string.Join(", ", payload.Select(value => value.Tag.ToString())) + " };");
                code.Line("    types = new global::System.Type[] { "
                    + string.Join(", ", payload.Select(value => "typeof(" + VisualBridgeDebugTypeMapping.CSharpTypeName(value.DeclaredType) + ")"))
                    + " };");
                code.Line("    return true;");
            }

            code.Line("default:");
            code.Line("    names = null;");
            code.Line("    tags = null;");
            code.Line("    types = null;");
            code.Line("    return false;");
            code.Close();
            code.Close();

            foreach (var method in model.Methods)
            {
                var payload = method.PayloadParameters.ToArray();
                code.Blank();
                code.Line("private static bool Dispatch" + method.Name + "(" + RequestType + " request, object[] parameters)");
                code.Open();
                code.Line("if (s_implementation == null)");
                code.Open();
                code.Line("return false;");
                code.Close();
                if (payload.Length != 0)
                {
                    code.Line("if (parameters == null || parameters.Length != " + payload.Length + ")");
                    code.Open();
                    code.Line("return false;");
                    code.Close();
                }

                code.Line("try");
                code.Open();
                var call = "s_implementation." + VisualBridgeDebugTypeMapping.CSharpIdentifier(method.Name) + "(request";
                for (var index = 0; index < payload.Length; index++)
                {
                    call += ", (" + VisualBridgeDebugTypeMapping.CSharpTypeName(payload[index].DeclaredType) + ")parameters[" + index + "]";
                }

                call += ")";
                if (method.ResultIsVoid)
                {
                    code.Line(call + ";");
                    code.Line("return " + model.ClassName + ".Send" + method.Name + "Result(request);");
                }
                else
                {
                    code.Line("var result = " + call + ";");
                    code.Line("return " + model.ClassName + ".Send" + method.Name + "Result(request, result);");
                }

                code.Close();
                code.Line("catch (global::System.Exception exception)");
                code.Open();
                code.Line(DebugApi + ".RejectRequest(request, \"handler-exception: \" + exception.GetType().Name);");
                code.Line("return false;");
                code.Close();
                code.Close();
            }

            code.Close();
            if (model.GeneratedNamespace.Length != 0)
            {
                code.Close();
            }

            code.Raw("#endif");
            return Plan(
                projectRoot,
                model.GeneratedDirectory + "/" + DispatcherName(model) + ".g.cs",
                code.ToString());
        }

        private static string ResultSignature(VisualBridgeDebugMethodModel method)
        {
            var parts = new List<string> { RequestType + " request" };
            if (method.ResultParameter != null)
            {
                parts.Add(VisualBridgeDebugTypeMapping.CSharpTypeName(method.ResultParameter.DeclaredType) + " result");
            }

            return string.Join(", ", parts);
        }

        private static string Signature(IEnumerable<VisualBridgeDebugParameterModel> parameters, bool includeDefaults)
        {
            return string.Join(", ", parameters.Select(parameter =>
                VisualBridgeDebugTypeMapping.CSharpTypeName(parameter.DeclaredType) + " "
                + VisualBridgeDebugTypeMapping.CSharpIdentifier(parameter.Name)
                + (includeDefaults && parameter.HasDefaultValue
                    ? " = " + VisualBridgeDebugTypeMapping.CSharpDefaultLiteral(parameter)
                    : string.Empty)));
        }

        private static string Arguments(IEnumerable<VisualBridgeDebugParameterModel> parameters)
        {
            return string.Join(", ", parameters.Select(
                parameter => VisualBridgeDebugTypeMapping.CSharpIdentifier(parameter.Name)));
        }

        private static string ImplementationName(VisualBridgeDebugInterfaceModel model)
        {
            return "VisualBridgeGenerated" + model.ClassName;
        }

        private static string DispatcherName(VisualBridgeDebugInterfaceModel model)
        {
            return "VisualBridgeGenerated" + model.ClassName + "Dispatcher";
        }

        private static string Literal(string value)
        {
            return JsonConvert.ToString(value ?? string.Empty);
        }

        private static VisualBridgeDebugPlannedFile Plan(string projectRoot, string relativePath, string text)
        {
            var fullPath = VisualBridgeDebugGeneratorPaths.ToFullPath(projectRoot, relativePath);
            return new VisualBridgeDebugPlannedFile(relativePath, fullPath, text);
        }

        /// <summary>小号代码生成器：固定 4 空格缩进、LF、行尾不留空格。</summary>
        private sealed class CodeBuilder
        {
            private readonly StringBuilder _builder = new StringBuilder();
            private int _indent;

            public void Line(string text)
            {
                if (text.Length == 0)
                {
                    _builder.Append('\n');
                    return;
                }

                _builder.Append(' ', _indent * 4).Append(text).Append('\n');
            }

            public void Blank()
            {
                _builder.Append('\n');
            }

            /// <summary>预处理指令等必须顶格的行。</summary>
            public void Raw(string text)
            {
                _builder.Append(text).Append('\n');
            }

            public void Open()
            {
                Line("{");
                _indent++;
            }

            public void Close()
            {
                _indent--;
                Line("}");
            }

            public override string ToString()
            {
                return _builder.ToString();
            }
        }
    }
