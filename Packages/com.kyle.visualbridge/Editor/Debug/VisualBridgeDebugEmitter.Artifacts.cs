        /// <summary>契约格式版本（附录 B.5 的 <c>manifest.schemaVersion = 2</c>）。</summary>
        private const int ContractSchemaVersion = 2;

        private static VisualBridgeDebugPlannedFile EmitContractsJson(
            VisualBridgeDebugDefinitionModel definition,
            string contractHash,
            string projectRoot,
            string artifactsRootRelative)
        {
            var builder = new StringBuilder();
            builder.Append("{\n");
            // JSON 不能写 // 注释，用同名键保留产物标记（解析方忽略未知键）。
            builder.Append("  \"//\": ").Append(Literal("// <auto-generated />")).Append(",\n");
            // 附录 B.5 的 manifest.schemaVersion = 2（契约文件格式版本）。
            builder.Append("  \"manifest\": { \"schemaVersion\": ")
                .Append(ContractSchemaVersion.ToString(CultureInfo.InvariantCulture))
                .Append(" },\n");
            builder.Append("  \"contractHash\": ").Append(Literal(contractHash)).Append(",\n");
            if (definition.Categories.Count == 0)
            {
                builder.Append("  \"categories\": [],\n");
            }
            else
            {
                builder.Append("  \"categories\": [\n");
                for (var categoryIndex = 0; categoryIndex < definition.Categories.Count; categoryIndex++)
                {
                    var category = definition.Categories[categoryIndex];
                    builder.Append("    {\n");
                    builder.Append("      \"name\": ").Append(Literal(category.Name)).Append(",\n");
                    builder.Append("      \"typeName\": ").Append(Literal(category.TypeName)).Append(",\n");
                    builder.Append("      \"fileBaseName\": ").Append(Literal(category.FileBaseName)).Append(",\n");
                    builder.Append("      \"generatedDirectory\": ").Append(Literal(category.GeneratedDirectory)).Append(",\n");
                    builder.Append("      \"interfaces\": [\n");
                    for (var interfaceIndex = 0; interfaceIndex < category.Interfaces.Count; interfaceIndex++)
                    {
                        var contractInterface = category.Interfaces[interfaceIndex];
                        builder.Append("        {\n");
                        builder.Append("          \"name\": ").Append(Literal(contractInterface.InterfaceName)).Append(",\n");
                        builder.Append("          \"fullName\": ").Append(Literal(contractInterface.InterfaceFullName)).Append(",\n");
                        builder.Append("          \"kind\": ").Append(Literal(contractInterface.KindText)).Append(",\n");
                        builder.Append("          \"className\": ").Append(Literal(contractInterface.ClassName)).Append(",\n");
                        builder.Append("          \"namespace\": ").Append(Literal(contractInterface.GeneratedNamespace)).Append(",\n");
                        AppendMethods(builder, contractInterface);
                        builder.Append("        }");
                        builder.Append(interfaceIndex + 1 < category.Interfaces.Count ? ",\n" : "\n");
                    }

                    builder.Append("      ]\n");
                    builder.Append("    }");
                    builder.Append(categoryIndex + 1 < definition.Categories.Count ? ",\n" : "\n");
                }

                builder.Append("  ],\n");
            }

            if (definition.Enums.Count == 0)
            {
                builder.Append("  \"enums\": []\n");
            }
            else
            {
                builder.Append("  \"enums\": [\n");
                for (var enumIndex = 0; enumIndex < definition.Enums.Count; enumIndex++)
                {
                    var contractEnum = definition.Enums[enumIndex];
                    builder.Append("    {\n");
                    builder.Append("      \"name\": ").Append(Literal(contractEnum.FullName)).Append(",\n");
                    builder.Append("      \"underlyingType\": ").Append(Literal(contractEnum.UnderlyingType)).Append(",\n");
                    builder.Append("      \"members\": [\n");
                    for (var memberIndex = 0; memberIndex < contractEnum.Members.Count; memberIndex++)
                    {
                        var member = contractEnum.Members[memberIndex];
                        builder.Append("        { \"name\": ").Append(Literal(member.Key))
                            .Append(", \"value\": ").Append(member.Value.ToString(CultureInfo.InvariantCulture)).Append(" }");
                        builder.Append(memberIndex + 1 < contractEnum.Members.Count ? ",\n" : "\n");
                    }

                    builder.Append("      ]\n");
                    builder.Append("    }");
                    builder.Append(enumIndex + 1 < definition.Enums.Count ? ",\n" : "\n");
                }

                builder.Append("  ]\n");
            }

            builder.Append("}\n");
            return Plan(projectRoot, artifactsRootRelative + "/debug-contracts.json", builder.ToString());
        }

        private static void AppendMethods(StringBuilder builder, VisualBridgeDebugInterfaceModel contractInterface)
        {
            builder.Append("          \"methods\": [");
            if (contractInterface.Methods.Count == 0)
            {
                builder.Append("]\n");
                return;
            }

            builder.Append('\n');
            for (var methodIndex = 0; methodIndex < contractInterface.Methods.Count; methodIndex++)
            {
                var method = contractInterface.Methods[methodIndex];
                builder.Append("            {\n");
                builder.Append("              \"name\": ").Append(Literal(method.Name)).Append(",\n");
                builder.Append("              \"id\": ").Append(method.MethodId.ToString(CultureInfo.InvariantCulture)).Append(",\n");
                builder.Append("              \"returnType\": ").Append(Literal(method.ResultContractType)).Append(",\n");
                if (method.ResultParameter != null)
                {
                    builder.Append("              \"result\": { \"name\": ").Append(Literal(method.ResultParameter.Name))
                        .Append(", \"type\": ").Append(Literal(method.ResultParameter.ContractType))
                        .Append(", \"tag\": ").Append(method.ResultParameter.Tag.ToString(CultureInfo.InvariantCulture))
                        .Append(" },\n");
                }

                builder.Append("              \"parameters\": [");
                var parameters = method.Parameters;
                if (parameters.Count == 0)
                {
                    builder.Append("]\n");
                }
                else
                {
                    builder.Append('\n');
                    for (var parameterIndex = 0; parameterIndex < parameters.Count; parameterIndex++)
                    {
                        var parameter = parameters[parameterIndex];
                        var role = parameter.IsInstance ? "instance" : parameter.IsRequest ? "request" : "payload";
                        builder.Append("                { \"name\": ").Append(Literal(parameter.Name))
                            .Append(", \"type\": ").Append(Literal(parameter.ContractType));
                        // 实例参数与请求句柄不进入载荷，也就没有二进制 tag。
                        if (role == "payload")
                        {
                            builder.Append(", \"tag\": ").Append(parameter.Tag.ToString(CultureInfo.InvariantCulture));
                        }

                        builder.Append(", \"role\": ").Append(Literal(role))
                            .Append(", \"optional\": ").Append(parameter.Optional ? "true" : "false")
                            .Append(" }");
                        builder.Append(parameterIndex + 1 < parameters.Count ? ",\n" : "\n");
                    }

                    builder.Append("              ]\n");
                }

                builder.Append("            }");
                builder.Append(methodIndex + 1 < contractInterface.Methods.Count ? ",\n" : "\n");
            }

            builder.Append("          ]\n");
        }

        private static VisualBridgeDebugPlannedFile EmitGlobalCSharp(
            string contractHash,
            string projectRoot,
            string artifactsRootRelative)
        {
            var code = new CodeBuilder();
            code.Raw(Header);
            code.Line("namespace " + GeneratedNamespace);
            code.Open();
            code.Line("/// <summary>全局调试契约指纹（附录 B.5）：与 debug-contracts.json 的 contractHash 一致。</summary>");
            code.Line("public static class VisualBridgeDebugContract");
            code.Open();
            code.Line("/// <summary>分类/接口/方法/参数/枚举的规范化文本取 SHA-256 前 8 字节（16 位十六进制）。</summary>");
            code.Line("public const string Hash = " + Literal(contractHash) + ";");
            code.Close();
            code.Blank();
            code.Line("/// <summary>系统方法号段（附录 B.5）：0 保留、1/2 = Create/Finish、3–9 预留、10+ 业务分类。</summary>");
            code.Line("public enum VisualBridgeDebugSystemMethod : ushort");
            code.Open();
            code.Line("Create = 1,");
            code.Line("Finish = 2,");
            code.Close();
            code.Close();
            return Plan(projectRoot, artifactsRootRelative + "/VisualBridgeDebugContract.g.cs", code.ToString());
        }

        private static VisualBridgeDebugPlannedFile EmitIdsJson(
            VisualBridgeDebugIdState idsState,
            string projectRoot,
            string artifactsRootRelative)
        {
            return Plan(projectRoot, artifactsRootRelative + "/debug-ids.json", idsState.ToJson());
        }

        private static VisualBridgeDebugPlannedFile EmitCategoryTypeScript(
            VisualBridgeDebugCategoryModel category,
            VisualBridgeDebugDefinitionModel definition,
            string contractHash,
            string projectRoot)
        {
            var builder = new StringBuilder();
            builder.Append(Header);
            builder.Append("// 模块调试展示用的类型与常量（附录 B.5）；宿主不加载，运行期以 debug-contracts.json 为准。\n");
            builder.Append('\n');
            builder.Append("export const debugCategory = ").Append(JsonConvert.ToString(category.Name)).Append(" as const;\n");
            builder.Append("export const debugCategoryTypeName = ").Append(JsonConvert.ToString(category.TypeName)).Append(" as const;\n");
            builder.Append("export const debugContractHash = ").Append(JsonConvert.ToString(contractHash)).Append(" as const;\n");

            builder.Append('\n');
            builder.Append("export const debugMethodIds = {\n");
            for (var interfaceIndex = 0; interfaceIndex < category.Interfaces.Count; interfaceIndex++)
            {
                var contractInterface = category.Interfaces[interfaceIndex];
                builder.Append("  ").Append(JsonConvert.ToString(contractInterface.InterfaceName)).Append(": {\n");
                for (var methodIndex = 0; methodIndex < contractInterface.Methods.Count; methodIndex++)
                {
                    var method = contractInterface.Methods[methodIndex];
                    builder.Append("    ").Append(JsonConvert.ToString(method.Name)).Append(": ")
                        .Append(method.MethodId.ToString(CultureInfo.InvariantCulture))
                        .Append(methodIndex + 1 < contractInterface.Methods.Count ? ",\n" : "\n");
                }

                builder.Append("  }");
                builder.Append(interfaceIndex + 1 < category.Interfaces.Count ? ",\n" : "\n");
            }

            builder.Append("} as const;\n");

            foreach (var contractEnum in ReferencedEnums(category, definition))
            {
                builder.Append('\n');
                builder.Append("/** 枚举 ").Append(contractEnum.FullName).Append(" */\n");
                builder.Append("export const ").Append(contractEnum.TsName).Append(" = {\n");
                for (var memberIndex = 0; memberIndex < contractEnum.Members.Count; memberIndex++)
                {
                    var member = contractEnum.Members[memberIndex];
                    builder.Append("  ").Append(JsonConvert.ToString(member.Key)).Append(": ")
                        .Append(member.Value.ToString(CultureInfo.InvariantCulture))
                        .Append(memberIndex + 1 < contractEnum.Members.Count ? ",\n" : "\n");
                }

                builder.Append("} as const;\n");
                builder.Append("export type ").Append(contractEnum.TsName).Append(" = (typeof ")
                    .Append(contractEnum.TsName).Append(")[keyof typeof ").Append(contractEnum.TsName).Append("];\n");
            }

            foreach (var contractInterface in category.Interfaces)
            {
                foreach (var method in contractInterface.Methods)
                {
                    builder.Append('\n');
                    var payload = method.PayloadParameters.ToArray();
                    var instance = method.InstanceParameter;
                    builder.Append("/** ").Append(contractInterface.InterfaceName).Append('.').Append(method.Name)
                        .Append(" 的载荷参数");
                    if (instance != null)
                    {
                        builder.Append("（实例参数 ").Append(instance.Name).Append(" 不进入载荷）");
                    }

                    builder.Append(" */\n");
                    builder.Append("export interface ").Append(contractInterface.ClassName).Append(method.Name).Append("Payload {\n");
                    foreach (var parameter in payload)
                    {
                        builder.Append("  ").Append(parameter.Name)
                            .Append(parameter.Optional ? "?" : string.Empty)
                            .Append(": ").Append(TsTypeOf(parameter)).Append(";\n");
                    }

                    builder.Append("}\n");
                    if (method.ResultParameter != null)
                    {
                        builder.Append("\nexport type ").Append(contractInterface.ClassName).Append(method.Name)
                            .Append("Result = ").Append(TsTypeOf(method.ResultParameter)).Append(";\n");
                    }
                    else if (method.ResultIsVoid)
                    {
                        builder.Append("\nexport type ").Append(contractInterface.ClassName).Append(method.Name)
                            .Append("Result = void;\n");
                    }
                }
            }

            return Plan(projectRoot, category.GeneratedDirectory + "/" + category.Name + ".g.ts", builder.ToString());
        }

        private static string TsTypeOf(VisualBridgeDebugParameterModel parameter)
        {
            return parameter.Kind == VisualBridgeDebugValueKind.Enum
                ? VisualBridgeDebugTypeMapping.TsEnumName(VisualBridgeDebugTypeMapping.FullName(parameter.DeclaredType))
                : parameter.TsType;
        }

        private static IEnumerable<VisualBridgeDebugEnumModel> ReferencedEnums(
            VisualBridgeDebugCategoryModel category,
            VisualBridgeDebugDefinitionModel definition)
        {
            var names = new HashSet<string>(StringComparer.Ordinal);
            foreach (var method in category.Interfaces.SelectMany(value => value.Methods))
            {
                foreach (var parameter in method.PayloadParameters.Where(
                             value => value.Kind == VisualBridgeDebugValueKind.Enum))
                {
                    names.Add(VisualBridgeDebugTypeMapping.FullName(parameter.DeclaredType));
                }

                if (method.ResultParameter != null && method.ResultParameter.Kind == VisualBridgeDebugValueKind.Enum)
                {
                    names.Add(VisualBridgeDebugTypeMapping.FullName(method.ResultParameter.DeclaredType));
                }
            }

            return definition.Enums.Where(value => names.Contains(value.FullName));
        }
